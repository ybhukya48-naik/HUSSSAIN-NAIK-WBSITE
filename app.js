function renderPastYear(year) {
  pastGrid.innerHTML = "";
  pastServices[year].forEach((item) => {
    pastGrid.insertAdjacentHTML("beforeend", cardTemplate(item, `Year ${year}`));
  });
  document.querySelectorAll(".year-tab").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.year === year);
  });
}

years.forEach((year, i) => {
  const btn = document.createElement("button");
  btn.className = `year-tab${i === 0 ? " active" : ""}`;
  btn.type = "button";
  btn.dataset.year = year;
  btn.textContent = year;
  btn.addEventListener("click", () => renderPastYear(year));
  yearTabs.appendChild(btn);
});

