function instagramCaptionFromPath(path, index) {
  const fileName = path.split("/").pop() || `photo-${index + 1}`;
  return fileName
    .replace(/\.[a-zA-Z0-9]+$/, "")
    .replace(/[-_]+/g, " ")
    .replace(/\b\d+\b/g, "")
    .replace(/\s+/g, " ")
    .trim() || `Instagram photo ${index + 1}`;
}

