function cardTemplate(item, badge) {
  const imageMarkup = item.image
    ? `<img src="${item.image}" alt="${item.title}" loading="lazy">`
    : "";

  const sourceMarkup = item.sourceUrl
    ? `<p class="source-link"><a href="${item.sourceUrl}" target="_blank" rel="noopener noreferrer">Read Full Report &#8599;</a></p>`
    : "";

  return `
    <article class="card">
      ${imageMarkup}
      <div class="card-body">
        <span class="badge">${badge}</span>
        <h3>${item.title}</h3>
        <p>${item.caption}</p>
        ${sourceMarkup}
      </div>
    </article>
  `;
}
function shortTitleFromUrl(url) {
  const last = url.split("/").pop() || "photo";
  return last
    .replace(/\.[a-zA-Z0-9]+$/, "")
    .replace(/[-_]+/g, " ")
    .replace(/\b\d{1,4}x\d{1,4}\b/g, "")
    .replace(/\b\d+\b/g, "")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 56);
}

