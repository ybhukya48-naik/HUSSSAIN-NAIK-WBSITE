const MAX_INSTAGRAM_STREAM_ITEMS = 80;
const MAX_WEBSITE_STREAM_ITEMS = 80;
const MAX_ALL_STREAM_ITEMS = 160;

function limitItems(items, max) {
  return items.length > max ? items.slice(0, max) : items;
}

function renderPhotoTrack(filter = "all") {
  const selected =
    filter === "instagram"
      ? limitItems(instagramStreamItems, MAX_INSTAGRAM_STREAM_ITEMS)
      : filter === "website"
        ? limitItems(websiteStreamItems, MAX_WEBSITE_STREAM_ITEMS)
        : limitItems(
            [
              ...limitItems(instagramStreamItems, MAX_INSTAGRAM_STREAM_ITEMS),
              ...limitItems(websiteStreamItems, MAX_WEBSITE_STREAM_ITEMS)
            ],
            MAX_ALL_STREAM_ITEMS
          );

  const trackItems = [...selected, ...selected];
  photoTrack.innerHTML = trackItems
    .map(
      (item) => `
        <article class="scroll-card" data-image="${item.image}" data-title="${item.title.replace(/"/g, "&quot;")}" data-link="${item.link}">
          <img src="${item.image}" alt="${item.title}" loading="lazy" decoding="async" fetchpriority="low">
          
        </article>
      `
    )
    .join("");
}

